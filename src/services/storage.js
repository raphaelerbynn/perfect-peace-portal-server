// B17: file storage for photos, documents and the school logo.
//
// Files live in a private object store (MinIO in Docker, STORAGE_DRIVER=s3) or
// on the server's disk under UPLOAD_DIR (STORAGE_DRIVER=local, the default when
// nothing is set: tests, cPanel). Never at a public address: the database
// stores only the key, and the API streams a file after checking who is asking.
//
// Every upload is checked here:
//   - size (multer stops reading past the limit; checked again here);
//   - real type from the file's first bytes (the browser's Content-Type and
//     the file name are ignored), only the types the kind allows;
//   - keys are generated by the server (random), never from the file name;
//   - images are decoded and re-encoded with sharp (see processImage): photos
//     become a 512px WebP plus a 128px thumbnail, and EXIF / GPS / device
//     metadata is dropped from every image. A file that only looks like an
//     image (right first bytes, broken inside) is refused.
import fs from "fs";
import fsp from "fs/promises";
import path from "path";
import crypto from "crypto";
import multer from "multer";
import { CreateBucketCommand, DeleteObjectCommand, GetObjectCommand, HeadBucketCommand, PutObjectCommand, S3Client } from "@aws-sdk/client-s3";
import { AppError } from "../utils/errorHandling.js";

const MB = 1024 * 1024;

const TYPE_LABEL = {
  "image/jpeg": "JPEG",
  "image/png": "PNG",
  "image/webp": "WebP",
  "application/pdf": "PDF",
};
const EXT = { "image/jpeg": "jpg", "image/png": "png", "image/webp": "webp", "application/pdf": "pdf" };
export const MIME_FOR_EXT = Object.fromEntries(Object.entries(EXT).map(([m, e]) => [e, m]));

const IMAGES = ["image/jpeg", "image/png", "image/webp"];

// Per-kind rules (SchoolPro asset-presets). Limits are on the upload; what is
// stored is the processed image (smaller). PDFs are stored as uploaded.
export const PRESETS = {
  photo: { folder: "photos", maxBytes: 5 * MB, types: IMAGES },
  document: { folder: "documents", maxBytes: 10 * MB, types: [...IMAGES, "application/pdf"] },
  logo: { folder: "branding", maxBytes: 2 * MB, types: IMAGES },
};

// --- Magic bytes ---------------------------------------------------------
// The real type from the content. Returns null for anything else (HTML, SVG,
// scripts, Office files, zips...).
export const sniffMime = (buf) => {
  if (!Buffer.isBuffer(buf) || buf.length < 12) return null;
  if (buf.subarray(0, 5).toString("latin1") === "%PDF-") return "application/pdf";
  if (buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return "image/jpeg";
  if (buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return "image/png";
  if (buf.subarray(0, 4).toString("latin1") === "RIFF" && buf.subarray(8, 12).toString("latin1") === "WEBP") return "image/webp";
  return null;
};

// --- File names (display only; never used for the key or the path) -------
export const cleanFileName = (name) => {
  const base = String(name ?? "").split(/[\\/]/).pop() || "";
  const cleaned = base
    .replace(/[\u0000-\u001f\u007f]/g, "")
    .replace(/[^\w.\- ()]+/g, "")
    .replace(/^\.+/, "")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 120);
  return cleaned || "file";
};

// --- Validation ----------------------------------------------------------
const limitText = (bytes) => `${Math.round(bytes / MB)} MB`;
const typesText = (types) => types.map((t) => TYPE_LABEL[t]).join(", ").replace(/, ([^,]*)$/, " or $1");

export const validateUpload = (file, kind) => {
  const preset = PRESETS[kind];
  if (!preset) throw new AppError("Unknown upload kind", 500);
  if (!file || !Buffer.isBuffer(file.buffer) || file.buffer.length === 0) {
    throw new AppError("Choose a file to upload", 400);
  }
  if (file.buffer.length > preset.maxBytes) {
    throw new AppError(`That file is too large. The limit is ${limitText(preset.maxBytes)}.`, 413);
  }
  const mime = sniffMime(file.buffer);
  if (!mime || !preset.types.includes(mime)) {
    throw new AppError(`That file type is not allowed. Upload a ${typesText(preset.types)} file.`, 415);
  }
  return { mime, ext: EXT[mime], size: file.buffer.length, originalName: cleanFileName(file.originalname) };
};

// Multer for one file in field "file", in memory, stopping at the kind's
// limit. Run it only AFTER the auth and permission checks, so nobody can make
// the server read a body they aren't allowed to send.
export const uploadOne = (kind) => {
  const preset = PRESETS[kind];
  const mw = multer({
    storage: multer.memoryStorage(),
    limits: { fileSize: preset.maxBytes, files: 1, fields: 5, fieldSize: 1024, parts: 8 },
  }).single("file");
  return (req, res, next) =>
    mw(req, res, (err) => {
      if (!err) return next();
      if (err.code === "LIMIT_FILE_SIZE") {
        return next(new AppError(`That file is too large. The limit is ${limitText(preset.maxBytes)}.`, 413));
      }
      if (err instanceof multer.MulterError) return next(new AppError("Upload one file in the \"file\" field.", 400));
      return next(new AppError("The upload could not be read. Try again.", 400));
    });
};

// --- Keys and paths ------------------------------------------------------
const KEY_RE = /^(photos|documents|branding)\/\d{4}\/[a-f0-9]{32}(-thumb)?\.(jpg|png|webp|pdf)$/;
const newKey = (folder, ext, suffix = "") =>
  `${folder}/${new Date().getUTCFullYear()}/${crypto.randomBytes(16).toString("hex")}${suffix}.${ext}`;
export const isValidKey = (key) => typeof key === "string" && KEY_RE.test(key);

export const uploadRoot = () => path.resolve(process.env.UPLOAD_DIR || path.join(process.cwd(), "uploads"));

// A key -> absolute path, refusing anything that isn't a server-made key or
// that would land outside the upload folder (path traversal).
export const keyToPath = (key, root = uploadRoot()) => {
  if (!isValidKey(key)) throw new AppError("File not found", 404);
  const full = path.resolve(root, key);
  if (!full.startsWith(root + path.sep)) throw new AppError("File not found", 404);
  return full;
};

export const localDriver = {
  name: "local",
  async put(buffer, { folder, ext, suffix }) {
    const key = newKey(folder, ext, suffix);
    const full = keyToPath(key);
    await fsp.mkdir(path.dirname(full), { recursive: true, mode: 0o750 });
    const tmp = `${full}.part`;
    await fsp.writeFile(tmp, buffer, { flag: "wx", mode: 0o640 });
    await fsp.rename(tmp, full);
    return key;
  },
  async open(key) {
    const full = keyToPath(key);
    let st;
    try {
      st = await fsp.lstat(full);
    } catch (e) {
      if (e.code === "ENOENT") throw new AppError("File not found", 404);
      throw e;
    }
    if (!st.isFile()) throw new AppError("File not found", 404); // no symlinks, no folders
    return { stream: fs.createReadStream(full), size: st.size };
  },
  async remove(key) {
    if (!isValidKey(key)) return;
    try {
      await fsp.unlink(keyToPath(key));
    } catch (e) {
      if (e.code !== "ENOENT") throw e;
    }
  },
};

// --- Object store (MinIO / S3 / R2) ---------------------------------------
// Private bucket; the API reads objects with its own credentials and streams
// them (no presigned URLs, so MinIO never needs a public address).
const isNotFound = (e) =>
  e?.name === "NoSuchKey" || e?.name === "NotFound" || e?.Code === "NoSuchKey" || e?.$metadata?.httpStatusCode === 404;

export const createS3Driver = ({ client, bucket }) => ({
  name: "s3",
  bucket,
  client,
  async put(buffer, { folder, ext, suffix }) {
    const key = newKey(folder, ext, suffix);
    const send = () =>
      client.send(new PutObjectCommand({ Bucket: bucket, Key: key, Body: buffer, ContentLength: buffer.length, ContentType: MIME_FOR_EXT[ext] }));
    try {
      await send();
    } catch (e) {
      // The store lost its bucket (a wiped test volume): make it again, once.
      if (e?.name !== "NoSuchBucket" && e?.Code !== "NoSuchBucket") throw e;
      await this.ensureBucket();
      await send();
    }
    return key;
  },
  async open(key) {
    if (!isValidKey(key)) throw new AppError("File not found", 404);
    let out;
    try {
      out = await client.send(new GetObjectCommand({ Bucket: bucket, Key: key }));
    } catch (e) {
      if (isNotFound(e)) throw new AppError("File not found", 404);
      throw e;
    }
    return { stream: out.Body, size: Number(out.ContentLength) };
  },
  async remove(key) {
    if (!isValidKey(key)) return;
    await client.send(new DeleteObjectCommand({ Bucket: bucket, Key: key })); // no error if already gone
  },
  // The bucket must exist (and stays private: MinIO buckets have no
  // anonymous policy unless one is set).
  async ensureBucket() {
    try {
      await client.send(new HeadBucketCommand({ Bucket: bucket }));
    } catch (e) {
      if (!isNotFound(e)) throw e;
      await client.send(new CreateBucketCommand({ Bucket: bucket }));
      console.log(`Storage: created bucket "${bucket}"`);
    }
  },
});

// STORAGE_DRIVER=local (default) | s3 (alias: minio). s3 needs S3_ENDPOINT,
// S3_BUCKET, S3_ACCESS_KEY, S3_SECRET_KEY; S3_REGION defaults to us-east-1 and
// path-style addressing is on unless S3_FORCE_PATH_STYLE=false (MinIO needs it).
export const storageConfigFromEnv = (env = process.env) => {
  const kind = String(env.STORAGE_DRIVER || "local").trim().toLowerCase();
  if (kind === "local" || kind === "") return { kind: "local" };
  if (kind !== "s3" && kind !== "minio") throw new Error(`STORAGE_DRIVER must be "local" or "s3", not "${env.STORAGE_DRIVER}"`);
  const missing = ["S3_ENDPOINT", "S3_BUCKET", "S3_ACCESS_KEY", "S3_SECRET_KEY"].filter((k) => !String(env[k] || "").trim());
  if (missing.length) throw new Error(`STORAGE_DRIVER=s3 needs ${missing.join(", ")}`);
  return {
    kind: "s3",
    endpoint: env.S3_ENDPOINT.trim(),
    region: (env.S3_REGION || "us-east-1").trim(),
    bucket: env.S3_BUCKET.trim(),
    accessKeyId: env.S3_ACCESS_KEY.trim(),
    secretAccessKey: env.S3_SECRET_KEY.trim(),
    forcePathStyle: String(env.S3_FORCE_PATH_STYLE ?? "true").toLowerCase() !== "false",
  };
};

export const createDriverFromConfig = (cfg) => {
  if (cfg.kind !== "s3") return localDriver;
  const client = new S3Client({
    endpoint: cfg.endpoint,
    region: cfg.region,
    forcePathStyle: cfg.forcePathStyle,
    credentials: { accessKeyId: cfg.accessKeyId, secretAccessKey: cfg.secretAccessKey },
    // Only checksum when the store asks (MinIO / R2 / older S3 compatibles).
    requestChecksumCalculation: "WHEN_REQUIRED",
    responseChecksumValidation: "WHEN_REQUIRED",
  });
  return createS3Driver({ client, bucket: cfg.bucket });
};

// At boot: pick the driver from the environment. A wrong setting stops the
// server (better than accepting uploads into the wrong place); an object store
// that is not reachable yet is retried, then logged (the rest of the API runs).
export const initStorage = async ({ env = process.env, retries = 10, delayMs = 3000 } = {}) => {
  const cfg = storageConfigFromEnv(env);
  const d = createDriverFromConfig(cfg);
  setStorageDriver(d);
  if (cfg.kind !== "s3") {
    console.log(`Storage: local disk (${uploadRoot()})`);
    return d;
  }
  for (let i = 1; i <= retries; i += 1) {
    try {
      await d.ensureBucket();
      console.log(`Storage: object store ${cfg.endpoint}, bucket "${cfg.bucket}"`);
      return d;
    } catch (e) {
      if (i === retries) {
        console.error(`Storage: object store ${cfg.endpoint} not reachable (${e?.name || e?.message}); uploads will fail until it is`);
        return d;
      }
      await new Promise((r) => setTimeout(r, delayMs));
    }
  }
  return d;
};

export const storageDriverName = () => driver.name;

let driver = localDriver;
export const setStorageDriver = (d) => {
  driver = d || localDriver;
};

export const storage = {
  put: (buffer, opts) => driver.put(buffer, opts),
  open: (key) => driver.open(key),
  // Removing an old file must never fail the request that replaced it.
  remove: async (key) => {
    if (!key) return;
    try {
      await driver.remove(key);
    } catch (e) {
      console.error("Could not remove stored file", key, e?.message);
    }
  },
};

// --- Image processing (sharp) --------------------------------------------
// Decoding is capped (no decompression bombs) and libvips' cache is off (a
// small VPS). .rotate() turns the pixels the right way up from the EXIF
// orientation; sharp writes no metadata unless asked, so EXIF (GPS, device),
// XMP and IPTC are gone from every stored image.
// sharp is a native module, loaded on the first image (not at start): if it
// can't load on a host (old glibc on a shared cPanel server), uploads of
// images answer 503 and the rest of the API still runs.
let sharpLib = null;
const loadSharp = async () => {
  if (sharpLib) return sharpLib;
  try {
    const mod = await import("sharp");
    const lib = mod.default || mod;
    lib.cache(false);
    lib.concurrency(1); // one libvips thread per job: a small VPS, predictable memory
    sharpLib = lib;
    return lib;
  } catch (e) {
    console.error("Storage: the image library (sharp) could not be loaded:", e?.message);
    throw new AppError("Image uploads are not available on this server right now. Ask the system administrator.", 503);
  }
};
// 50 MP: any phone photo shrunk to the 5 MB photo limit, or a 600 dpi A4 scan.
// Checked from the file header before decoding (cheap), and again by sharp.
const MAX_INPUT_PIXELS = 50_000_000;
const ENCODE = {
  "image/jpeg": (img) => img.jpeg({ quality: 88, mozjpeg: true }),
  "image/png": (img) => img.png({ compressionLevel: 9 }),
  "image/webp": (img) => img.webp({ quality: 88 }),
};
const SIZES = { photo: 512, thumb: 128, logo: 1024, document: 3000 };
const TOO_MANY_PIXELS = "That image is too large (too many pixels). Take a smaller photo or scan.";

const decode = (sharp, buffer) => sharp(buffer, { limitInputPixels: MAX_INPUT_PIXELS, failOn: "error" }).rotate();
const fit = (img, px) => img.resize({ width: px, height: px, fit: "inside", withoutEnlargement: true });

// At most one image is decoded at a time (B17 review: a few parallel uploads
// of a small, huge-dimension PNG could otherwise exhaust memory).
let imageQueue = Promise.resolve();
const oneAtATime = (job) => {
  const run = imageQueue.then(job, job);
  imageQueue = run.catch(() => {});
  return run;
};

const processImageNow = async (buffer, mime, kind) => {
  const sharp = await loadSharp();
  try {
    const { width = 0, height = 0 } = await sharp(buffer).metadata(); // header only
    if (!width || !height) throw new Error("no size");
    if (width * height > MAX_INPUT_PIXELS) throw new AppError(TOO_MANY_PIXELS, 413);
    if (kind === "photo") {
      // Decode the original once; the thumbnail is made from the 512px result.
      const main = await fit(decode(sharp, buffer), SIZES.photo).webp({ quality: 82 }).toBuffer();
      const thumb = await sharp(main)
        .resize({ width: SIZES.thumb, height: SIZES.thumb, fit: "cover", position: "attention" })
        .webp({ quality: 75 })
        .toBuffer();
      return [
        { buffer: main, mime: "image/webp", ext: "webp" },
        { buffer: thumb, mime: "image/webp", ext: "webp", suffix: "-thumb" },
      ];
    }
    const out = await ENCODE[mime](fit(decode(sharp, buffer), SIZES[kind] || SIZES.document)).toBuffer();
    return [{ buffer: out, mime, ext: EXT[mime] }];
  } catch (e) {
    if (e instanceof AppError) throw e;
    if (/pixel limit/i.test(String(e?.message))) throw new AppError(TOO_MANY_PIXELS, 413);
    throw new AppError("That image could not be read. It may be damaged; try another file.", 415);
  }
};

// Returns the files to store: [{ buffer, mime, ext, suffix? }]. Photos: a
// 512px WebP and a 128px square thumbnail (cropped to the centre, for lists).
// Logos and image documents keep their type, sized down, metadata stripped.
// PDFs are stored as uploaded.
export const processImage = (buffer, mime, kind) => {
  if (!IMAGES.includes(mime)) return Promise.resolve([{ buffer, mime, ext: EXT[mime] }]);
  return oneAtATime(() => processImageNow(buffer, mime, kind));
};

// Save a validated upload. Returns { key, thumbKey (photos), mime, ext, size,
// originalName } where mime/ext/size describe what was stored. If storing the
// second file fails, the first is removed again (no orphans).
export const saveUpload = async (file, kind) => {
  const info = validateUpload(file, kind);
  const parts = await processImage(file.buffer, info.mime, kind);
  const keys = [];
  try {
    for (const p of parts) {
      keys.push(await storage.put(p.buffer, { folder: PRESETS[kind].folder, ext: p.ext, suffix: p.suffix }));
    }
  } catch (e) {
    await Promise.all(keys.map((k) => storage.remove(k)));
    throw e;
  }
  const main = parts[0];
  return {
    ...info,
    key: keys[0],
    thumbKey: keys[1] || null,
    mime: main.mime,
    ext: main.ext,
    size: main.buffer.length,
  };
};

const FILE_HEADERS = ["Content-Type", "Content-Length", "Cache-Control", "Content-Security-Policy", "Content-Disposition"];

// Stream a stored file to the response. Private by default: no caching by
// shared caches, no sniffing, no scripts, download name cleaned.
// The file is always closed: when the download finishes, when the client
// aborts it (public GET /school/logo must not leak file descriptors) and when
// reading fails. A read error before any byte was sent is thrown (the caller's
// error handler answers); after that nothing can be sent, so the response is
// cut off and the promise resolves (never next(err) once headers are out).
export const sendStoredFile = async (res, { key, mime, name, cache = "private, no-store" }) => {
  const { stream, size } = await storage.open(key);
  if (res.destroyed || res.writableEnded) {
    stream.destroy(); // the client left while the file was being opened
    return;
  }
  const ext = key.split(".").pop();
  res.setHeader("Content-Type", MIME_FOR_EXT[ext] || mime || "application/octet-stream");
  res.setHeader("Content-Length", size);
  res.setHeader("Cache-Control", cache);
  res.setHeader("X-Content-Type-Options", "nosniff");
  res.setHeader("Content-Security-Policy", "default-src 'none'; sandbox");
  const safe = cleanFileName(name || `file.${ext}`);
  res.setHeader("Content-Disposition", `inline; filename="${safe.replace(/"/g, "")}"; filename*=UTF-8''${encodeURIComponent(safe)}`);
  await new Promise((resolve, reject) => {
    let settled = false;
    const settle = (fn, value) => {
      if (settled) return;
      settled = true;
      fn(value);
    };
    // 'close' follows 'finish' on a completed response and fires alone on an
    // aborted one: either way the file is released.
    res.on("close", () => {
      stream.destroy();
      settle(resolve);
    });
    stream.on("error", (err) => {
      stream.destroy();
      if (res.headersSent) {
        res.destroy();
        settle(resolve);
        return;
      }
      if (typeof stream.unpipe === "function") stream.unpipe(res);
      FILE_HEADERS.forEach((h) => res.removeHeader(h));
      settle(reject, err);
    });
    stream.pipe(res);
  });
};
